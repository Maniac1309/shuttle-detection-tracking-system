from fastapi import FastAPI, UploadFile, File, HTTPException
from fastapi.responses import FileResponse
from fastapi.middleware.cors import CORSMiddleware
from ultralytics import YOLO
import imageio_ffmpeg

import shutil
import os
import subprocess
import uuid

app = FastAPI()

# ---------------- CORS ---------------- #

app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5500",
        "http://127.0.0.1:5500",
        "*"  # Keep "*" during local debugging to rule out CORS blocks
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# ---------------- PATHS ---------------- #

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "best.pt")

UPLOAD_DIR = os.path.join(BASE_DIR, "uploads")
OUTPUT_DIR = os.path.join(BASE_DIR, "outputs")
os.makedirs(UPLOAD_DIR, exist_ok=True)
os.makedirs(OUTPUT_DIR, exist_ok=True)

# ---------------- MODEL ---------------- #

model = YOLO(MODEL_PATH)

# ---------------- PREDICT ---------------- #

@app.post("/predict")
def predict(file: UploadFile = File(...)):
    # Use a unique run name so files never collide
    run_id = str(uuid.uuid4())
    safe_filename = os.path.basename(file.filename)
    file_path = os.path.join(UPLOAD_DIR, f"{run_id}_{safe_filename}")

    with open(file_path, "wb") as buffer:
        shutil.copyfileobj(file.file, buffer)

    results = model.predict(
        source=file_path,
        save=True,
        conf=0.25,
        project=OUTPUT_DIR,
        name=run_id
    )

    save_dir = str(results[0].save_dir)

    # Locate the actual saved file regardless of whether YOLO changed the extension
    saved_files = os.listdir(save_dir)
    if not saved_files:
        raise HTTPException(status_code=500, detail="Prediction output file not found.")

    output_path = os.path.join(save_dir, saved_files[0])
    print("OUTPUT:", output_path)

    return FileResponse(output_path)

# ---------------- TRACK ---------------- #

@app.post("/track")
def track(file: UploadFile = File(...)):
    run_id = str(uuid.uuid4())
    safe_filename = os.path.basename(file.filename)
    file_path = os.path.join(UPLOAD_DIR, f"{run_id}_{safe_filename}")

    with open(file_path, "wb") as buffer:
        shutil.copyfileobj(file.file, buffer)

    results = model.track(
        source=file_path,
        save=True,
        conf=0.25,
        project=OUTPUT_DIR,
        name=run_id,
        persist=True
    )

    save_dir = str(results[0].save_dir)
    print("TRACK SAVE DIR:", save_dir)

    # Find whatever video file YOLO generated (.avi, .mp4, .mkv, etc.)
    raw_video = None
    for f in os.listdir(save_dir):
        if f.lower().endswith((".avi", ".mp4", ".mov", ".mkv", ".webm")):
            raw_video = os.path.join(save_dir, f)
            break

    if raw_video is None:
        raise HTTPException(status_code=500, detail="No output video generated by YOLO.")

    mp4_file = os.path.join(save_dir, "tracked_video.mp4")

# Inside your @app.post("/track") function, replace the cmd block with:
    ffmpeg_path = imageio_ffmpeg.get_ffmpeg_exe()

    cmd = [
        ffmpeg_path, "-y",
        "-i", raw_video,
        "-c:v", "libx264",
        "-pix_fmt", "yuv420p",
        "-movflags", "+faststart",
        mp4_file
    ]
    subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)

    if not os.path.exists(mp4_file):
        raise HTTPException(status_code=500, detail="FFmpeg conversion failed.")

    return FileResponse(
        mp4_file,
        media_type="video/mp4",
        filename="tracked_video.mp4"
    )